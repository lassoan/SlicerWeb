// What a segment is: its colour in the list opens the terminology selector; a search finds a type
// wherever its category; choosing one names the segment after it and colours it as the terminology
// recommends; a name or colour of one's own is kept as such, with a button back to the terminology's.
// Usage: node tests/segment-editor-terminology.mjs [url] [screenshot.png]
import { chromium } from "playwright-core";

const base = process.argv[2] ?? "http://localhost:5173/";
const shot = process.argv.find((a) => a.endsWith(".png"));
const browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await (await browser.newContext({ viewport: { width: 1500, height: 1000 } })).newPage();
page.on("pageerror", (e) => console.log("[pageerror] " + String(e).slice(0, 200)));
await page.goto(base + "?sample=CTChest");
await page.waitForFunction(() => /CT-chest/.test(document.body.innerText) && document.querySelector("#slicer-view-Red"), null, { timeout: 300000 });
await page.waitForTimeout(3000);
const value = (expr) => page.evaluate((c) => window.slicerWeb.bridge.evalPython(c, "eval"), expr);
const text = async (expr) => String(await value(expr)).replace(/^['"]|['"]$/g, "");
const fail = [];
const check = (name, ok, detail) => {
  console.log(`${ok ? "PASS" : "FAIL"} ${name}${detail === undefined ? "" : ": " + detail}`);
  if (!ok) fail.push(name);
};
const segment = (what) => text(`(lambda s: ${what})(__import__("slicer").util.getNodesByClass("vtkMRMLSegmentationNode")[0].GetSegmentation().GetNthSegment(0))`);
const nameAndColour = () => segment('"%s|%s|%s|%s" % (s.GetName(), "#%02x%02x%02x" % tuple(int(c * 255 + 0.5) for c in s.GetColor()), s.GetNameAutoGenerated(), s.GetColorAutoGenerated())');

// the module opens on a segmentation of its own, and a segment to name
await page.getByRole("button", { name: "Segment Editor" }).first().click();
await page.waitForTimeout(2500);
const panel = page.locator(".sw-panel-scroll").last();
await panel.locator("button", { hasText: /^Add$/ }).first().click();
await page.waitForTimeout(1200);
const segmentRow = page.locator("[data-name='segmentRow']").first();
const nameBefore = (await segmentRow.locator("[data-name='segmentName']").innerText()).trim();
await segmentRow.locator("[data-name='segmentColor']").click();
await page.waitForTimeout(1500);
const dialog = page.locator("[data-name='terminologySelector']");
check("the segment's colour opens what it is", await dialog.count() > 0);
check("typing goes to the search box first", await page.evaluate(() => document.activeElement?.getAttribute("data-name")) === "terminologySearch");
const heightBefore = (await dialog.boundingBox())?.height ?? 0;
const categories = await page.locator("[data-name='terminologyCategories'] button").allInnerTexts();
check("it offers the categories of the terminology", categories.length > 1, categories.slice(0, 4).join(", "));

// a search is for a type, wherever its category: "liver" finds Liver
await page.locator("[data-name='terminologySearch']").fill("liver");
await page.waitForTimeout(800);
const types = page.locator("[data-name='terminologyTypes'] button");
const typeNames = await types.allInnerTexts();
check("searching for liver lists the type", typeNames.some((t) => /^Liver$/i.test(t.trim())), typeNames.slice(0, 4).join(", "));
check("and the dialog keeps its height with few types listed", Math.abs(((await dialog.boundingBox())?.height ?? 0) - heightBefore) < 4, `${heightBefore} -> ${(await dialog.boundingBox())?.height}`);
const wanted = Math.max(0, typeNames.findIndex((t) => /^Liver$/i.test(t.trim())));
await types.nth(wanted).click();
await page.waitForTimeout(600);
const chosen = (await types.nth(wanted).innerText()).trim();
check("the name box shows the terminology's name", (await page.locator("[data-name='terminologyName']").inputValue()) === chosen);
check("with nothing to reset yet", await page.locator("[data-name='terminologyNameReset']").isDisabled());
await page.locator("[data-name='terminologyApply']").click();
await page.waitForTimeout(1500);
check("choosing one closes the selector", (await page.locator("[data-name='terminologySelector']").count()) === 0);
const nameAfter = await segment("s.GetName()");
check("the segment is named after what it is", nameAfter === chosen && nameAfter !== nameBefore,
  `"${nameBefore}" -> "${nameAfter}" (chose "${chosen}")`);
const tag = await text(`
(lambda s, v: (s.GetTag(__import__("slicer").vtkSegment.GetTerminologyEntryTagName(), v), str(v))[1])(
    __import__("slicer").util.getNodesByClass("vtkMRMLSegmentationNode")[0].GetSegmentation().GetNthSegment(0),
    __import__("vtk").reference(""))`);
check("and carries the terminology entry", tag.includes("~SCT^") && tag.includes(chosen), tag.slice(0, 110));
const colour = await segment('"#%02x%02x%02x" % tuple(int(c * 255 + 0.5) for c in s.GetColor())');
check("and the colour the terminology recommends", /^#[0-9a-f]{6}$/.test(colour) && colour !== "#000000", colour);
if (shot) await page.screenshot({ path: shot });

// A name and a colour of one's own, and the buttons back to the terminology's
await segmentRow.locator("[data-name='segmentColor']").click();
await page.waitForTimeout(1200);
await page.locator("[data-name='terminologyColor']").fill("#123456");
await page.locator("[data-name='terminologyName']").fill("Liver (my own)");
await page.waitForTimeout(300);
check("a name of one's own can be reset", await page.locator("[data-name='terminologyNameReset']").isEnabled());
check("and so can a colour", await page.locator("[data-name='terminologyColorReset']").isEnabled());
// Enter, in the name box, takes what is chosen
await page.locator("[data-name='terminologyName']").press("Enter");
await page.waitForTimeout(1500);
check("Enter takes it", (await page.locator("[data-name='terminologySelector']").count()) === 0);
check("the segment takes the name and colour of one's own, marked as such", (await nameAndColour()) === "Liver (my own)|#123456|False|False", await nameAndColour());
await segmentRow.locator("[data-name='segmentColor']").click();
await page.waitForTimeout(1200);
check("opened again, the boxes show them", (await page.locator("[data-name='terminologyName']").inputValue()) === "Liver (my own)");
check("and typing goes to the name of one's own", await page.evaluate(() => document.activeElement?.getAttribute("data-name")) === "terminologyName");
await page.locator("[data-name='terminologyNameReset']").click();
await page.locator("[data-name='terminologyColorReset']").click();
await page.waitForTimeout(200);
check("reset, the name is the terminology's again", (await page.locator("[data-name='terminologyName']").inputValue()) === chosen);
// Enter, in the search box, takes what is chosen as well
await page.locator("[data-name='terminologySearch']").press("Enter");
await page.waitForTimeout(1500);
check("and the segment is back to the terminology's name and colour", (await nameAndColour()) === `${chosen}|${colour}|True|True`, await nameAndColour());

await browser.close();
console.log(fail.length ? "FAILED: " + fail.join(", ") : "ALL PASSED");
